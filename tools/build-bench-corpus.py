#!/usr/bin/env python3
"""Generate js/bench-cases.js from eval/router-cases.json.

The benchmark became runnable from inside the app in v9.17, so the corpus has
to ship. It is NOT the same file: every `why` is stripped out. Those reasons
exist so a human reading the repo can argue with a LABEL, and they are the
bulk of the JSON -- shipping them would put several kilobytes of commentary
into every user's download for no runtime purpose.

Generated, never hand-edited. A test fails the build if the two drift.
"""
import json, sys

src = json.load(open('eval/router-cases.json'))
compact = {
    'today': src['today'],
    'names': (src.get('people') or []) + (src.get('lists') or []) + (src.get('chores') or []),
    'cases': [],
}
for c in src['cases']:
    row = {'id': c['id'], 'bucket': c['bucket'], 'sentence': c['sentence'], 'intent': c['intent']}
    if c.get('params'):      row['params'] = c['params']
    if c.get('mustNotHave'): row['mustNotHave'] = c['mustNotHave']
    compact['cases'].append(row)

# One line per case: compact enough not to bloat the download, still readable
# in a diff, which a single minified blob would not be.
lines = ',\n'.join('    ' + json.dumps(c, ensure_ascii=False) for c in compact['cases'])
body = ('{\n  today: %s,\n  names: %s,\n  cases: [\n%s\n  ],\n}'
        % (json.dumps(compact['today']), json.dumps(compact['names'], ensure_ascii=False), lines))
out = '''/**
 * The routing benchmark corpus, as the app carries it.
 *
 * GENERATED by tools/build-bench-corpus.py from eval/router-cases.json.
 * Do not edit by hand -- a test fails the build if the two disagree.
 *
 * Every `why` from the source file is stripped: those reasons exist so a
 * person reading the repo can argue with a LABEL, and they are most of the
 * file. Shipping them would put kilobytes of commentary into every download
 * for no runtime purpose. The labels themselves ship unchanged, so a run on
 * the phone and a run from the terminal are scored against the same answers.
 *
 * Why the app carries this at all: the API key lives in the phone's browser
 * storage, so a desktop script cannot reach the provider actually in use.
 * The only place the benchmark can measure what Logan really runs is here.
 */

export const BENCH = %s;
''' % body
open('js/bench-cases.js', 'w').write(out)
print('wrote js/bench-cases.js (%d cases, %d bytes)' % (len(compact['cases']), len(out)))
